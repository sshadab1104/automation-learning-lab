package Java.J01_Variables_And_DataTypes.Day_02;

public class Ex02_DeclareVariable {
    public static void main(String[] args) {
        String employeeName = "Shadab";
        int employeeID = 9292;
        int salary = 20000;
        double experience = 6.5;
        boolean isPermanentEmployee = true;
        System.out.println("Employee Name: "+employeeName);
        System.out.println("Employee ID: "+employeeID);
        System.out.println("Salary: "+salary);
        System.out.println("Experience: "+experience);
        System.out.println("Is Permanent Employee: "+isPermanentEmployee);
    }
}
